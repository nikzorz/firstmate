size_of() { LC_ALL=C wc -c < "$1" | tr -d '[:space:]'; }

# --- bare turn-end, unverifiable harness: pane churn is the third proof --------
# A harness whose semantic busy state has no verified source (codex) can never
# report working, so the two proofs above are unreachable for it and EVERY worker
# turn boundary woke firstmate. Pane content that changed since the previous poll
# is harness-independent positive evidence the crew is still executing - the same
# liveness input the stale backbone already trusts - so a bare turn-end from a
# churning pane is benign. The pane going quiet afterwards is still caught by that
# backbone, which is why this widens the proof rather than bounding the wake rate.

# The pane-churn turn-end absorb is opt-in per home, so every case that exercises
# it (whether it expects an absorb or one of the guards that must still surface)
# points the watcher at a case-local config dir holding the flag. A case that must
# NOT have it points at an empty one, so no developer's real config can leak in.
churn_config() {  # <dir> [off]
  local cfg="$1/config"
  mkdir -p "$cfg"
  [ "${2:-}" = off ] || : > "$cfg/turnend-churn-absorb"
  printf '%s\n' "$cfg"
}

# Wait until the watcher records an absorbed wake matching <needle> in its triage
# log. 1 if the watcher exits first (i.e. it surfaced the wake instead), which is
# exactly the unfixed behavior this case exists to catch. Polls the log rather
# than a poll cycle so the assertion lands inside the FIRST poll, long before an
# unchanging fixture pane could reach the stale backbone.
wait_for_absorbed() {  # <state> <pid> <needle>
  local state=$1 pid=$2 needle=$3 i=0
  while [ "$i" -lt 100 ]; do
    grep -Fq "$needle" "$state/.watch-triage.log" 2>/dev/null && return 0
    kill -0 "$pid" 2>/dev/null || return 1
    sleep 0.1
    i=$((i + 1))
  done
  return 1
}

# --- wedge threshold reached while the run step is still advancing ------------
# The wedge timer measured pane idleness alone, so a crew whose validation run
# was demonstrably moving - a fix step that takes far longer than the escalation
# window - was escalated as a possible wedge while fm-crew-state.sh could see the
# run advancing at that same moment. Reaching the threshold must ask the run
# itself, over a confirmed-live endpoint, and restart the window while it is
# still advancing. A run that has STOPPED advancing still escalates: the phase B
# of the two tests above reports `stalled` over a live endpoint.

# One watcher round over a lane already absorbed at its recorded hash with the
# wedge timer running, so every round starts at the threshold. The endpoint is a
# live claude agent unless the case clears FM_TEST_PANE_COMMAND.
advancing_round() {  # <state> <fakebin> <out> <capture> <window> [VAR=value...]
  local state=$1 fakebin=$2 out=$3 capture=$4 window=$5
  shift 5
  env "$@" PATH="$fakebin:$PATH" FM_FAKE_TMUX_WINDOW="$window" FM_FAKE_TMUX_CAPTURE="$capture" \
    FM_FAKE_TMUX_CURRENT_COMMAND="${FM_TEST_PANE_COMMAND-claude}" \
    FM_WATCH_HANDLING_SUCCESSOR=1 FM_CONFIG_OVERRIDE="$(dirname "$state")/config" \
    FM_STATE_OVERRIDE="$state" FM_CREW_STATE_BIN="$fakebin/fm-crew-state.sh" FM_STALE_ESCALATE_SECS=240 \
    FM_POLL=1 FM_SIGNAL_GRACE=1 FM_CHECK_INTERVAL=999999 FM_HEARTBEAT=999999 "$WATCH" > "$out" &
}

# A lane stably stale at its recorded hash, already absorbed as provably working
# (the suppressor holds the hash and the wedge timer is 500s old). <status-line>
# is the whole log; <meta-extra> is one more line of task metadata.
advancing_fixture() {  # <name> <window> <task> <status-line> [meta-extra]
  local name=$1 window=$2 task=$3 status=$4 extra=${5-} dir state key text
  dir=$(make_case "$name"); state="$dir/state"
  text='no-mistakes axi run: validating...'
  printf '%s' "$text" > "$dir/pane.txt"
  printf 'window=%s\nkind=ship\nbackend=tmux\n' "$window" > "$state/$task.meta"
  [ -z "$extra" ] || printf '%s\n' "$extra" >> "$state/$task.meta"
  printf '%s\n' "$status" > "$state/$task.status"
  prime_status_seen "$state" "$state/$task.status"
  key=$(printf '%s' "$window" | tr ':/.' '___')
  printf '%s' "$(hash_text "$text")" > "$state/.hash-$key"
  printf '1\n' > "$state/.count-$key"
  printf '%s' "$(hash_text "$text")" > "$state/.stale-$key"
  echo $(( $(date +%s) - 500 )) > "$state/.stale-since-$key"
  printf '%s\n' "$dir"
}

# --- stale pane, parked on an open decision: absorbed with NO wedge timer --------
# A crew parked at a review gate whose ask-user finding it escalated keeps
# reporting `parked` throughout: it cannot proceed until the answer comes back,
# so its pane is idle for exactly as long as that takes, and without this the
# stale path raised a wake on every new pane hash. Only a home that armed
# config/wedge-defer-parked-gate absorbs it, and only while the crew's own last
# line is the needs-decision still open for the run its gate names.
parked_decision_fixture() {  # <name> <window> <task> <status-log> <flag|noflag>
  local name=$1 window=$2 task=$3 log=$4 flag=$5 dir state key
  dir=$(make_case "$name"); state="$dir/state"
  mkdir -p "$dir/config"
  [ "$flag" = flag ] && : > "$dir/config/wedge-defer-parked-gate"
  printf 'awaiting a decision on 1 finding' > "$dir/pane.txt"
  printf 'window=%s\nkind=ship\nharness=claude\nbackend=tmux\n' "$window" > "$state/$task.meta"
  printf '%s\n' "$log" > "$state/$task.status"
  prime_status_seen "$state" "$state/$task.status"
  key=$(printf '%s' "$window" | tr ':/.' '___')
  printf '%s' "$(hash_text 'awaiting a decision on 1 finding')" > "$state/.hash-$key"
  printf '1\n' > "$state/.count-$key"
  printf '%s\n' "$dir"
}

